#!/usr/bin/env bash
# embed_helper.sh — Copy the thermaliq-helper binary and its launchd plist
# into the Tauri app bundle so SMJobBless can find them at runtime.
#
# Called from the Tauri `beforeBundleCommand` (or manually in CI after
# `cargo build --release`).
#
# Environment variables (all optional — sensible defaults are used):
#   APPLE_TEAM_ID       — 10-char Apple Developer Team ID (e.g. "A1B2C3D4E5")
#                         If unset the placeholder string is left verbatim,
#                         which is fine for unsigned/dev builds.
#   HELPER_BINARY       — Path to the compiled thermaliq-helper binary.
#                         Default: ../../target/release/thermaliq-helper
#   APP_BUNDLE          — Path to the .app bundle to embed into.
#                         Default: auto-detected from `find . -name "*.app"`
#
# Exit codes:
#   0  — success
#   1  — fatal error (missing binary, plist, etc.)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"

# ── Locate the helper binary ─────────────────────────────────────────────────

HELPER_BINARY="${HELPER_BINARY:-${REPO_ROOT}/target/release/thermaliq-helper}"

if [[ ! -f "${HELPER_BINARY}" ]]; then
    echo "embed_helper.sh: ERROR — helper binary not found at ${HELPER_BINARY}"
    echo "  Build it first: cargo build --release -p thermaliq-helper"
    exit 1
fi

# ── Locate the app bundle ────────────────────────────────────────────────────

if [[ -z "${APP_BUNDLE:-}" ]]; then
    # Tauri places the .app in target/release/bundle/macos/
    APP_BUNDLE="$(find "${REPO_ROOT}/target/release/bundle/macos" -maxdepth 1 -name "*.app" 2>/dev/null | head -1)"
fi

if [[ -z "${APP_BUNDLE}" || ! -d "${APP_BUNDLE}" ]]; then
    echo "embed_helper.sh: WARNING — app bundle not found; skipping embedding."
    echo "  This is expected during 'cargo build' without 'tauri build'."
    exit 0
fi

echo "embed_helper.sh: embedding helper into ${APP_BUNDLE}"

# ── Create destination directory ─────────────────────────────────────────────

LAUNCH_SERVICES_DIR="${APP_BUNDLE}/Contents/Library/LaunchServices"
mkdir -p "${LAUNCH_SERVICES_DIR}"

# ── Copy helper binary ───────────────────────────────────────────────────────

HELPER_DST="${LAUNCH_SERVICES_DIR}/com.thermaliq.helper"
cp -f "${HELPER_BINARY}" "${HELPER_DST}"
chmod 544 "${HELPER_DST}"
echo "  Copied helper binary → ${HELPER_DST}"

# ── Determine helper version for staleness checks ────────────────────────────

HELPER_VERSION="$("${HELPER_BINARY}" --version 2>/dev/null | head -1 || echo "1.0.0")"
echo "  Helper version: ${HELPER_VERSION}"

# ── Substitute APPLE_TEAM_ID in Info.plist templates ─────────────────────────

TEAM_ID="${APPLE_TEAM_ID:-XXXXXXXXXX}"

# App-side Info.plist: already at Contents/Info.plist (generated by Tauri).
# Inject SMPrivilegedExecutables if not already present.
APP_INFO_PLIST="${APP_BUNDLE}/Contents/Info.plist"
TEMPLATE_INFO_PLIST="${SCRIPT_DIR}/../Info.plist"

if [[ -f "${TEMPLATE_INFO_PLIST}" ]]; then
    # Substitute team ID placeholder and merge into the Tauri-generated plist.
    MERGED_SNIPPET="$(sed "s/\${APPLE_TEAM_ID}/${TEAM_ID}/g" "${TEMPLATE_INFO_PLIST}")"

    # Use PlistBuddy to add/replace the SMPrivilegedExecutables key so we
    # don't clobber Tauri's existing keys.
    DR_STRING="$(echo "${MERGED_SNIPPET}" | \
        /usr/libexec/PlistBuddy -c "Print :SMPrivilegedExecutables:com.thermaliq.helper" /dev/stdin 2>/dev/null || echo "")"

    if [[ -n "${DR_STRING}" && -f "${APP_INFO_PLIST}" ]]; then
        # Remove existing key if present, then add fresh.
        /usr/libexec/PlistBuddy -c "Delete :SMPrivilegedExecutables" "${APP_INFO_PLIST}" 2>/dev/null || true
        /usr/libexec/PlistBuddy \
            -c "Add :SMPrivilegedExecutables dict" \
            -c "Add :SMPrivilegedExecutables:com.thermaliq.helper string ${DR_STRING}" \
            "${APP_INFO_PLIST}"
        echo "  Injected SMPrivilegedExecutables into ${APP_INFO_PLIST}"
    fi
fi

# Helper-side Info.plist: embed in the LaunchServices directory alongside
# the binary and also link into the binary's __TEXT,__info_plist section
# (requires re-linking — only done in release/signed builds).
HELPER_INFO_PLIST_SRC="${REPO_ROOT}/thermaliq-helper/Info.plist"
HELPER_INFO_PLIST_DST="${LAUNCH_SERVICES_DIR}/com.thermaliq.helper.plist"

if [[ -f "${HELPER_INFO_PLIST_SRC}" ]]; then
    sed "s/\${APPLE_TEAM_ID}/${TEAM_ID}/g" "${HELPER_INFO_PLIST_SRC}" > "${HELPER_INFO_PLIST_DST}"

    # Patch CFBundleShortVersionString to match the binary.
    /usr/libexec/PlistBuddy \
        -c "Set :CFBundleShortVersionString ${HELPER_VERSION}" \
        "${HELPER_INFO_PLIST_DST}" 2>/dev/null || true
    echo "  Wrote helper Info.plist → ${HELPER_INFO_PLIST_DST}"
fi

# ── Copy launchd plist ────────────────────────────────────────────────────────

LAUNCHD_PLIST_SRC="${SCRIPT_DIR}/../com.thermaliq.helper.plist"
LAUNCHD_PLIST_DST="${LAUNCH_SERVICES_DIR}/com.thermaliq.helper.launchd.plist"

if [[ -f "${LAUNCHD_PLIST_SRC}" ]]; then
    cp -f "${LAUNCHD_PLIST_SRC}" "${LAUNCHD_PLIST_DST}"
    echo "  Copied launchd plist → ${LAUNCHD_PLIST_DST}"
fi

# ── Embed plist into binary __TEXT,__info_plist section ──────────────────────
# This step requires a re-link; only viable in a full Xcode/CI build.
# We attempt it silently and skip if ld/libtool is unavailable.

if command -v ld &>/dev/null && [[ -f "${HELPER_INFO_PLIST_DST}" ]]; then
    ld -sectcreate __TEXT __info_plist "${HELPER_INFO_PLIST_DST}" \
        -o "${HELPER_DST}.tmp" \
        "${HELPER_DST}" 2>/dev/null && mv "${HELPER_DST}.tmp" "${HELPER_DST}" \
        && echo "  Embedded plist in __TEXT,__info_plist section" \
        || rm -f "${HELPER_DST}.tmp"
fi

# ── Final permissions ────────────────────────────────────────────────────────

chmod 544 "${HELPER_DST}"

echo "embed_helper.sh: done."
